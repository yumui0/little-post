	const DICT = lang === "fr" ? FR : null;
	const fill = (s, vars) => vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m)) : s;
	const t = (s, vars) => fill((DICT && DICT[s]) || s, vars);
	const locale = lang === "fr" ? "fr-FR" : "en-IE";
	window.I18N = { lang, t, locale };
	if (!DICT) return;

	/* ---------- swap fixed English text for French, now and whenever the page changes ---------- */
	const SKIP = "script, style, textarea, [translate='no']";
	const ATTRS = ["placeholder", "aria-label", "title", "alt"];
	// returns null when nothing changes, so writing the result back never re-triggers the observer forever
	const swap = s => { const k = s.trim(), v = k && DICT[k]; if (!v || v === k) return null; const i = s.indexOf(k); return s.slice(0, i) + v + s.slice(i + k.length); };
	const doText = n => { const p = n.parentElement; if (!p || p.closest(SKIP)) return; const v = swap(n.data); if (v !== null) n.data = v; };
	// a textarea's text is the customer's, but its placeholder is ours, so attributes only skip translate="no"
	const doAttrs = el => { if (el.closest("[translate='no']")) return; for (const a of ATTRS) { const cur = el.getAttribute(a); if (cur) { const v = swap(cur); if (v !== null) el.setAttribute(a, v); } } };
	const doTree = root => {
		if (root.nodeType === 3) return doText(root);
		if (root.nodeType !== 1) return;
		doAttrs(root);
		const w = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT);
		for (let n = w.nextNode(); n; n = w.nextNode()) n.nodeType === 3 ? doText(n) : doAttrs(n);
	};

	document.title = t(document.title);
	const meta = document.querySelector('meta[name="description"]'); if (meta) meta.content = t(meta.content);
	doTree(document.body);
	new MutationObserver(list => {
		for (const m of list) {
			if (m.type === "childList") m.addedNodes.forEach(doTree);
			else if (m.type === "characterData") doText(m.target);
			else doAttrs(m.target);
		}
	}).observe(document.body, { subtree: true, childList: true, characterData: true, attributes: true, attributeFilter: ATTRS });
