// Builds supabase/seed.sql from path.js so the database and the shelf always list the same cards.
import { readFileSync, writeFileSync } from "node:fs";
import vm from "node:vm";
const src = readFileSync(new URL("../path.js", import.meta.url), "utf8")
	.replace(/\bconst (SHOP|PRICE_CENTS)\b/g, "var $1");
const ctx = {}; vm.createContext(ctx); vm.runInContext(src, ctx);
const q = s => "'" + String(s).replace(/'/g, "''") + "'";
const rows = [];
for (const cat of ctx.SHOP.categories) for (const c of cat.cards)
	rows.push(`(${q(c.id)}, ${q(cat.title)}, ${q(c.name)}, ${q(c.caption || "")}, ${q(c.src)}, ${c.free ? 0 : ctx.PRICE_CENTS}, true)`);
writeFileSync(new URL("../supabase/seed.sql", import.meta.url),
`-- Generated by scripts/gen-seed.mjs. Re-run it after editing path.js, then run this file again (safe to repeat).
insert into public.cards (id, occasion, title, description, image_url, price_cents, published) values
${rows.join(",\n")}
on conflict (id) do update set occasion = excluded.occasion, title = excluded.title, description = excluded.description, image_url = excluded.image_url;
-- note: price_cents is deliberately NOT overwritten on re-run, so a price you changed in the database stays.
`);
console.log(rows.length, "cards written");
